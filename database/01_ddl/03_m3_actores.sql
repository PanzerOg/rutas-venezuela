BEGIN;

CREATE TABLE Actor_Usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY,
    contrasena_hash TEXT NOT NULL,
    tipo_actor VARCHAR(10) NOT NULL,
    CONSTRAINT PK_ACTOR_USUARIO PRIMARY KEY (id_usuario),
    CONSTRAINT DOM_ACTOR_USUARIO__HASH CHECK (btrim(contrasena_hash) <> ''),
    CONSTRAINT DOM_ACTOR_USUARIO__TIPO CHECK (tipo_actor IN ('Visitante', 'Guia', 'Comercio', 'Ente'))
);

CREATE TABLE Visitante (
    id_usuario INTEGER,
    doc_identidad VARCHAR(30) NOT NULL,
    tipo_documento VARCHAR(10) NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    pais_origen VARCHAR(80) NOT NULL,
    idioma_nativo VARCHAR(60) NOT NULL,
    tel_emergencia VARCHAR(30) NOT NULL,
    grupo_sanguineo VARCHAR(3) NOT NULL,
    id_reportante INTEGER NOT NULL,
    CONSTRAINT PK_VISITANTE PRIMARY KEY (id_usuario),
    CONSTRAINT AK_VISITANTE UNIQUE (tipo_documento, doc_identidad),
    CONSTRAINT AK_VISITANTE_REPORTANTE UNIQUE (id_reportante),
    CONSTRAINT FK_VISITANTE_ACTOR FOREIGN KEY (id_usuario)
        REFERENCES Actor_Usuario ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_VISITANTE_REPORTANTE FOREIGN KEY (id_reportante) REFERENCES Reportante ON UPDATE CASCADE,
    CONSTRAINT DOM_VISITANTE__TIPO_DOC CHECK (tipo_documento IN ('Cedula', 'Pasaporte')),
    CONSTRAINT DOM_VISITANTE__DOC CHECK (btrim(doc_identidad) <> ''),
    CONSTRAINT DOM_VISITANTE__SANGRE CHECK (grupo_sanguineo IN ('O+', 'O-', 'A+', 'A-', 'B+', 'B-', 'AB+', 'AB-'))
);

CREATE TABLE Accesibilidad_Visitante (
    id_usuario INTEGER,
    accesibilidad VARCHAR(120),
    CONSTRAINT PK_ACCESIBILIDAD_VISITANTE PRIMARY KEY (id_usuario, accesibilidad),
    CONSTRAINT FK_ACCESIBILIDAD_VISITANTE FOREIGN KEY (id_usuario)
        REFERENCES Visitante ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT DOM_ACCESIBILIDAD_VISITANTE__VALOR CHECK (btrim(accesibilidad) <> '')
);

CREATE TABLE Guia_Turistico (
    id_usuario INTEGER,
    nro_rtn VARCHAR(30) NOT NULL,
    cod_licencia VARCHAR(30) NOT NULL,
    acreditacion_oficial VARCHAR(200) NOT NULL,
    anios_trayectoria SMALLINT NOT NULL,
    tarifa_hora NUMERIC(12,2) NOT NULL,
    zona_asignada VARCHAR(150) NOT NULL,
    id_validador INTEGER NOT NULL,
    id_reportante INTEGER NOT NULL,
    CONSTRAINT PK_GUIA_TURISTICO PRIMARY KEY (id_usuario),
    CONSTRAINT AK_GUIA_TURISTICO UNIQUE (nro_rtn, cod_licencia),
    CONSTRAINT AK_GUIA_VALIDADOR UNIQUE (id_validador),
    CONSTRAINT AK_GUIA_REPORTANTE UNIQUE (id_reportante),
    CONSTRAINT FK_GUIA_TURISTICO_ACTOR FOREIGN KEY (id_usuario)
        REFERENCES Actor_Usuario ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_GUIA_TURISTICO_VALIDADOR FOREIGN KEY (id_validador) REFERENCES Validador_Acceso ON UPDATE CASCADE,
    CONSTRAINT FK_GUIA_TURISTICO_REPORTANTE FOREIGN KEY (id_reportante) REFERENCES Reportante ON UPDATE CASCADE,
    CONSTRAINT DOM_GUIA_TURISTICO__RTN CHECK (btrim(nro_rtn) <> ''),
    CONSTRAINT DOM_GUIA_TURISTICO__LICENCIA CHECK (btrim(cod_licencia) <> ''),
    CONSTRAINT DOM_GUIA_TURISTICO__ACREDITACION CHECK (btrim(acreditacion_oficial) <> ''),
    CONSTRAINT DOM_GUIA_TURISTICO__TRAYECTORIA CHECK (anios_trayectoria >= 0),
    CONSTRAINT DOM_GUIA_TURISTICO__TARIFA CHECK (tarifa_hora > 0 AND tarifa_hora <> 'NaN')
);

CREATE TABLE Especialidad_Guia (
    id_usuario INTEGER,
    especialidad VARCHAR(100),
    CONSTRAINT PK_ESPECIALIDAD_GUIA PRIMARY KEY (id_usuario, especialidad),
    CONSTRAINT FK_ESPECIALIDAD_GUIA_GUIA FOREIGN KEY (id_usuario)
        REFERENCES Guia_Turistico ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT DOM_ESPECIALIDAD_GUIA__ESPECIALIDAD CHECK (btrim(especialidad) <> '')
);

CREATE TABLE Idioma_Guia (
    id_usuario INTEGER,
    idioma VARCHAR(60),
    CONSTRAINT PK_IDIOMA_GUIA PRIMARY KEY (id_usuario, idioma),
    CONSTRAINT FK_IDIOMA_GUIA_GUIA FOREIGN KEY (id_usuario)
        REFERENCES Guia_Turistico ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT DOM_IDIOMA_GUIA__IDIOMA CHECK (btrim(idioma) <> '')
);

CREATE TABLE Comercio_Aliado (
    id_usuario INTEGER,
    rif_comercio VARCHAR(20) NOT NULL,
    razon_social VARCHAR(150) NOT NULL,
    categoria_comercial VARCHAR(80) NOT NULL,
    aforo INTEGER NOT NULL,
    nro_permiso_sanitario VARCHAR(40) NOT NULL,
    cuenta_bancaria VARCHAR(34) NOT NULL,
    cod_estado VARCHAR(6),
    cod_municipio VARCHAR(10),
    cod_parroquia VARCHAR(10),
    nombre_hito VARCHAR(150),
    id_elem_servicio INTEGER NOT NULL,
    id_validador INTEGER NOT NULL,
    CONSTRAINT PK_COMERCIO_ALIADO PRIMARY KEY (id_usuario),
    CONSTRAINT AK_COMERCIO_ALIADO_RIF UNIQUE (rif_comercio),
    CONSTRAINT AK_COMERCIO_ALIADO_RAZON UNIQUE (razon_social),
    CONSTRAINT AK_COMERCIO_SERV UNIQUE (id_elem_servicio),
    CONSTRAINT AK_COMERCIO_VAL UNIQUE (id_validador),
    CONSTRAINT FK_COMERCIO_ALIADO_ACTOR FOREIGN KEY (id_usuario)
        REFERENCES Actor_Usuario ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_COMERCIO_ALIADO_HITO FOREIGN KEY (cod_estado, cod_municipio, cod_parroquia, nombre_hito)
        REFERENCES Hito_Turistico MATCH FULL ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT FK_COMERCIO_ALIADO_SERV FOREIGN KEY (id_elem_servicio) REFERENCES Elemento_Servicio ON UPDATE CASCADE,
    CONSTRAINT FK_COMERCIO_ALIADO_VAL FOREIGN KEY (id_validador) REFERENCES Validador_Acceso ON UPDATE CASCADE,
    CONSTRAINT DOM_COMERCIO_ALIADO__RIF CHECK (btrim(rif_comercio) <> ''),
    CONSTRAINT DOM_COMERCIO_ALIADO__RAZON CHECK (btrim(razon_social) <> ''),
    CONSTRAINT DOM_COMERCIO_ALIADO__AFORO CHECK (aforo > 0)
);

CREATE TABLE Horario_Atencion_Comercio (
    id_usuario INTEGER,
    dia VARCHAR(15),
    apertura TIME,
    cierre TIME NOT NULL,
    CONSTRAINT PK_HORARIO_ATENCION_COMERCIO PRIMARY KEY (id_usuario, dia, apertura),
    CONSTRAINT FK_HORARIO_COMERCIO_COMERCIO FOREIGN KEY (id_usuario)
        REFERENCES Comercio_Aliado ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT DOM_HORARIO_COMERCIO__DIA CHECK (dia IN ('Lunes','Martes','Miercoles','Jueves','Viernes','Sabado','Domingo')),
    CONSTRAINT EXP_HORARIO_COMERCIO_R_1 CHECK (cierre > apertura)
);

CREATE TABLE Ente_Publico (
    id_usuario INTEGER,
    rif_institucional VARCHAR(20) NOT NULL,
    denominacion_oficial VARCHAR(150) NOT NULL,
    nivel_territorial VARCHAR(12) NOT NULL,
    funcionario_enlace VARCHAR(150) NOT NULL,
    decreto_adscripcion VARCHAR(100) NOT NULL,
    id_reportante INTEGER NOT NULL,
    CONSTRAINT PK_ENTE_PUBLICO PRIMARY KEY (id_usuario),
    CONSTRAINT AK_ENTE_PUBLICO_RIF UNIQUE (rif_institucional),
    CONSTRAINT AK_ENTE_PUBLICO_DENOM UNIQUE (denominacion_oficial),
    CONSTRAINT AK_ENTE_REPORTANTE UNIQUE (id_reportante),
    CONSTRAINT FK_ENTE_PUBLICO_ACTOR FOREIGN KEY (id_usuario)
        REFERENCES Actor_Usuario ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_ENTE_PUBLICO_REPORTANTE FOREIGN KEY (id_reportante) REFERENCES Reportante ON UPDATE CASCADE,
    CONSTRAINT DOM_ENTE_PUBLICO__RIF CHECK (btrim(rif_institucional) <> ''),
    CONSTRAINT DOM_ENTE_PUBLICO__DENOM CHECK (btrim(denominacion_oficial) <> ''),
    CONSTRAINT DOM_ENTE_PUBLICO__NIVEL CHECK (nivel_territorial IN ('Nacional', 'Estadal', 'Municipal', 'Parroquial'))
);

CREATE TABLE Tutela (
    id_usuario INTEGER,
    cod_estado VARCHAR(6),
    cod_municipio VARCHAR(10),
    cod_parroquia VARCHAR(10),
    nombre_hito VARCHAR(150),
    CONSTRAINT PK_TUTELA PRIMARY KEY (id_usuario, cod_estado, cod_municipio, cod_parroquia, nombre_hito),
    CONSTRAINT FK_TUTELA_ENTE FOREIGN KEY (id_usuario)
        REFERENCES Ente_Publico ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_TUTELA_HITO FOREIGN KEY (cod_estado, cod_municipio, cod_parroquia, nombre_hito)
        REFERENCES Hito_Turistico ON UPDATE CASCADE ON DELETE CASCADE
);

COMMIT;
