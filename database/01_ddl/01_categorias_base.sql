CREATE TABLE Punto_Itinerario (
    id_punto_itin INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT PK_PUNTO_ITINERARIO PRIMARY KEY (id_punto_itin)
);

CREATE TABLE Elemento_Afectable (
    id_elem_afectable INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT PK_ELEMENTO_AFECTABLE PRIMARY KEY (id_elem_afectable)
);

CREATE TABLE Objeto_Evaluable (
    id_obj_evaluable INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT PK_OBJETO_EVALUABLE PRIMARY KEY (id_obj_evaluable)
);

CREATE TABLE Elemento_Servicio (
    id_elem_servicio INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT PK_ELEMENTO_SERVICIO PRIMARY KEY (id_elem_servicio)
);

CREATE TABLE Validador_Acceso (
    id_validador INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT PK_VALIDADOR_ACCESO PRIMARY KEY (id_validador)
);

CREATE TABLE Reportante (
    id_reportante INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT PK_REPORTANTE PRIMARY KEY (id_reportante)
);
